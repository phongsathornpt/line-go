// Command genservices generates the typed LINEJS Thrift service catalog.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type endpoint struct {
	Path            string            `json:"endpoint"`
	ProtocolType    int               `json:"protocolType"`
	Methods         []string          `json:"methods"`
	MethodEndpoints map[string]string `json:"methodEndpoints"`
}

type serviceCatalog map[string]endpoint

func main() {
	manifestPath := flag.String("manifest", "spec/linejs_services.json", "LINEJS service endpoint manifest")
	schemaPath := flag.String("schema", "types/schema.json", "extracted LINE Thrift schema")
	outputPath := flag.String("output", "base/service_catalog_gen.go", "generated Go output")
	apiOutputPath := flag.String("api-output", "base/service_methods_gen.go", "generated typed service methods")
	flag.Parse()
	if err := run(*manifestPath, *schemaPath, *outputPath, *apiOutputPath); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(manifestPath, schemaPath, outputPath, apiOutputPath string) error {
	manifestBytes, err := os.ReadFile(manifestPath)
	if err != nil {
		return fmt.Errorf("read service manifest: %w", err)
	}
	var catalog serviceCatalog
	if err := json.Unmarshal(manifestBytes, &catalog); err != nil {
		return fmt.Errorf("decode service manifest: %w", err)
	}
	schemaBytes, err := os.ReadFile(schemaPath)
	if err != nil {
		return fmt.Errorf("read Thrift schema: %w", err)
	}
	var schema map[string]json.RawMessage
	if err := json.Unmarshal(schemaBytes, &schema); err != nil {
		return fmt.Errorf("decode Thrift schema: %w", err)
	}
	generated, err := generate(catalog, schema)
	if err != nil {
		return err
	}
	formatted, err := format.Source(generated)
	if err != nil {
		return fmt.Errorf("format service catalog: %w", err)
	}
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("write service catalog: %w", err)
	}
	generatedAPI, err := generateAPI(catalog, schema)
	if err != nil {
		return err
	}
	formattedAPI, err := format.Source(generatedAPI)
	if err != nil {
		return fmt.Errorf("format typed service methods: %w", err)
	}
	if err := os.WriteFile(apiOutputPath, formattedAPI, 0o644); err != nil {
		return fmt.Errorf("write typed service methods: %w", err)
	}
	services, methods := len(catalog), 0
	for _, service := range catalog {
		methods += len(service.Methods)
	}
	fmt.Printf("generated %d services and %d typed RPC methods in %s and %s\n", services, methods, outputPath, apiOutputPath)
	return nil
}

func generateAPI(catalog serviceCatalog, schema map[string]json.RawMessage) ([]byte, error) {
	serviceNames := make([]string, 0, len(catalog))
	for name := range catalog {
		serviceNames = append(serviceNames, name)
	}
	sort.Strings(serviceNames)
	var output bytes.Buffer
	output.WriteString("// Code generated by cmd/genservices; DO NOT EDIT.\n\npackage base\n\nimport (\n\t\"context\"\n\t\"fmt\"\n\n\t\"github.com/phongsathornpt/line-go/types\"\n)\n\n")
	for _, serviceName := range serviceNames {
		service := catalog[serviceName]
		receiverType := serviceName
		if serviceName != "AuthService" && serviceName != "TalkService" {
			fmt.Fprintf(&output, "// %s provides typed calls for %s.\ntype %s struct { rpc *RPCService }\n\n", receiverType, serviceName, receiverType)
			accessor := strings.TrimSuffix(serviceName, "Service")
			fmt.Fprintf(&output, "// %s returns the %s service.\nfunc (c *BaseClient) %s() *%s {\n\treturn &%s{rpc: c.services[%s]}\n}\n\n", accessor, serviceName, accessor, receiverType, receiverType, "ServiceName"+accessor)
		}
		methods := append([]string(nil), service.Methods...)
		sort.Strings(methods)
		for _, method := range methods {
			if reservedGeneratedMethod(serviceName, method) {
				continue
			}
			prefix := ""
			if serviceName == "SquareService" || serviceName == "SquareLiveTalkService" {
				prefix = "SquareService_"
			}
			argsName := goName(prefix + method + "_args")
			resultName := goName(prefix + method + "_result")
			if _, ok := schema[prefix+method+"_args"]; !ok {
				return nil, fmt.Errorf("service %q method %q has no args schema", serviceName, method)
			}
			if _, ok := schema[prefix+method+"_result"]; !ok {
				return nil, fmt.Errorf("service %q method %q has no result schema", serviceName, method)
			}
			methodName := goName(method)
			fmt.Fprintf(&output, "// %s calls the LINEJS %s RPC.\nfunc (s *%s) %s(ctx context.Context, args types.%s) (*types.%s, error) {\n", methodName, method, receiverType, methodName, argsName, resultName)
			fmt.Fprintf(&output, "\tif s == nil {\n\t\treturn nil, fmt.Errorf(\"line service: %s is nil\")\n\t}\n", receiverType)
			fmt.Fprintf(&output, "\tresult := new(types.%s)\n", resultName)
			fmt.Fprintf(&output, "\tif _, err := s.rpc.CallTyped(ctx, %q, args, result); err != nil {\n\t\treturn nil, err\n\t}\n\treturn result, nil\n}\n\n", method)
		}
	}
	return output.Bytes(), nil
}

func reservedGeneratedMethod(serviceName, method string) bool {
	switch serviceName {
	case "AuthService":
		return method == "refresh" || method == "reportRefreshedAccessToken"
	case "TalkService":
		return method == "sync" || method == "sendMessage" || method == "fetchOperations"
	default:
		return false
	}
}

func goName(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool {
		return !('a' <= r && r <= 'z') && !('A' <= r && r <= 'Z') && !('0' <= r && r <= '9')
	})
	var name strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		name.WriteString(strings.ToUpper(part[:1]))
		name.WriteString(part[1:])
	}
	result := name.String()
	if result != "" && '0' <= result[0] && result[0] <= '9' {
		result = "X" + result
	}
	return result
}

func generate(catalog serviceCatalog, schema map[string]json.RawMessage) ([]byte, error) {
	serviceNames := make([]string, 0, len(catalog))
	for name := range catalog {
		serviceNames = append(serviceNames, name)
	}
	sort.Strings(serviceNames)

	var output bytes.Buffer
	output.WriteString("// Code generated by cmd/genservices; DO NOT EDIT.\n\npackage base\n\nimport \"github.com/phongsathornpt/line-go/thrift\"\n\n")
	output.WriteString("const (\n")
	for _, name := range serviceNames {
		constant := "ServiceName" + strings.TrimSuffix(name, "Service")
		fmt.Fprintf(&output, "\t%s ServiceName = %q\n", constant, name)
	}
	output.WriteString(")\n\nvar linejsServiceCatalog = []ServiceDefinition{\n")

	totalMethods := 0
	for _, name := range serviceNames {
		service := catalog[name]
		if service.Path == "" {
			return nil, fmt.Errorf("service %q has no endpoint", name)
		}
		protocolName, ok := map[int]string{3: "thrift.ProtocolBinary", 4: "thrift.ProtocolCompact"}[service.ProtocolType]
		if !ok {
			return nil, fmt.Errorf("service %q has unsupported protocol %d", name, service.ProtocolType)
		}
		methods := append([]string(nil), service.Methods...)
		sort.Strings(methods)
		for _, method := range methods {
			if !hasMethodSchema(name, method, schema) {
				return nil, fmt.Errorf("service %q method %q has no args/result schema", name, method)
			}
		}
		totalMethods += len(methods)
		fmt.Fprintf(&output, "\t{\n\t\tName: %s,\n\t\tEndpoint: %q,\n\t\tProtocol: %s,\n\t\tMethods: []string{\n", "ServiceName"+strings.TrimSuffix(name, "Service"), service.Path, protocolName)
		for _, method := range methods {
			fmt.Fprintf(&output, "\t\t\t%q,\n", method)
		}
		output.WriteString("\t\t},\n")
		if len(service.MethodEndpoints) > 0 {
			methodsWithOverride := make([]string, 0, len(service.MethodEndpoints))
			for method, path := range service.MethodEndpoints {
				if !contains(methods, method) {
					return nil, fmt.Errorf("service %q has an endpoint override for unknown method %q", name, method)
				}
				if !strings.HasPrefix(path, "/") {
					return nil, fmt.Errorf("service %q method %q endpoint must start with /", name, method)
				}
				methodsWithOverride = append(methodsWithOverride, method)
			}
			sort.Strings(methodsWithOverride)
			output.WriteString("\t\tMethodEndpoints: map[string]string{\n")
			for _, method := range methodsWithOverride {
				fmt.Fprintf(&output, "\t\t\t%q: %q,\n", method, service.MethodEndpoints[method])
			}
			output.WriteString("\t\t},\n")
		}
		output.WriteString("\t},\n")
	}
	output.WriteString("}\n")
	if totalMethods == 0 {
		return nil, fmt.Errorf("service catalog has no typed RPC methods")
	}
	return output.Bytes(), nil
}

func contains(values []string, wanted string) bool {
	for _, value := range values {
		if value == wanted {
			return true
		}
	}
	return false
}

func hasMethodSchema(serviceName, method string, schema map[string]json.RawMessage) bool {
	args := method + "_args"
	result := method + "_result"
	if serviceName == "SquareService" || serviceName == "SquareLiveTalkService" {
		args = "SquareService_" + args
		result = "SquareService_" + result
	}
	_, hasArgs := schema[args]
	_, hasResult := schema[result]
	return hasArgs && hasResult
}
