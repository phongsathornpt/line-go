// Command gentypes generates public Go LINE DTOs and enum constants from the
// schema extracted from packages/types/thrift.ts.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

type enumMember struct {
	value int64
	name  string
}

type fieldDefinition struct {
	ID     int             `json:"fid"`
	Name   string          `json:"name"`
	Type   json.RawMessage `json:"type"`
	Struct string          `json:"struct"`
	List   json.RawMessage `json:"list"`
	Set    json.RawMessage `json:"set"`
	Map    json.RawMessage `json:"map"`
	Key    json.RawMessage `json:"key"`
	Binary bool            `json:"binary"`
}

type generator struct {
	structs map[string][]fieldDefinition
	enums   map[string][]enumMember
}

func main() {
	schemaPath := flag.String("schema", "types/schema.json", "path to extracted LINE Thrift JSON schema")
	outputPath := flag.String("output", "types/models_gen.go", "generated Go output path")
	flag.Parse()

	if err := run(*schemaPath, *outputPath); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(schemaPath, outputPath string) error {
	data, err := os.ReadFile(schemaPath)
	if err != nil {
		return fmt.Errorf("read schema: %w", err)
	}
	g, err := parseSchema(data)
	if err != nil {
		return err
	}
	generated, err := g.generate()
	if err != nil {
		return err
	}
	formatted, err := format.Source(generated)
	if err != nil {
		return fmt.Errorf("format generated types: %w", err)
	}
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("write generated types: %w", err)
	}
	fmt.Printf("generated %d structs and %d enums in %s\n", len(g.structs), len(g.enums), outputPath)
	return nil
}

func parseSchema(data []byte) (*generator, error) {
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(data, &raw); err != nil {
		return nil, fmt.Errorf("decode schema: %w", err)
	}
	g := &generator{
		structs: make(map[string][]fieldDefinition),
		enums:   make(map[string][]enumMember),
	}
	for name, definition := range raw {
		trimmed := bytes.TrimSpace(definition)
		if len(trimmed) == 0 {
			return nil, fmt.Errorf("schema entry %q is empty", name)
		}
		if trimmed[0] == '[' {
			var fields []fieldDefinition
			if err := json.Unmarshal(trimmed, &fields); err != nil {
				return nil, fmt.Errorf("decode struct %q: %w", name, err)
			}
			g.structs[name] = fields
			continue
		}
		members, err := parseEnum(name, trimmed)
		if err != nil {
			return nil, err
		}
		g.enums[name] = members
	}
	return g, nil
}

func parseEnum(name string, data []byte) ([]enumMember, error) {
	var values map[string]json.RawMessage
	if err := json.Unmarshal(data, &values); err != nil {
		return nil, fmt.Errorf("decode enum %q: %w", name, err)
	}
	members := make([]enumMember, 0, len(values)/2)
	for key, rawValue := range values {
		value, err := strconv.ParseInt(key, 10, 64)
		if err != nil {
			continue
		}
		if value < math.MinInt32 || value > math.MaxInt32 {
			return nil, fmt.Errorf("enum %q value %d is outside i32 range", name, value)
		}
		var label string
		if err := json.Unmarshal(rawValue, &label); err != nil {
			return nil, fmt.Errorf("enum %q value %d is not a string label", name, value)
		}
		members = append(members, enumMember{value: value, name: label})
	}
	sort.Slice(members, func(i, j int) bool {
		if members[i].value == members[j].value {
			return members[i].name < members[j].name
		}
		return members[i].value < members[j].value
	})
	return members, nil
}

func (g *generator) generate() ([]byte, error) {
	var output strings.Builder
	output.WriteString("// Code generated by cmd/gentypes; DO NOT EDIT.\n\n")
	output.WriteString("package types\n\n")

	typeNames := make(map[string]string, len(g.structs)+len(g.enums))
	for name := range g.structs {
		if err := addTypeName(typeNames, name); err != nil {
			return nil, err
		}
	}
	for name := range g.enums {
		if err := addTypeName(typeNames, name); err != nil {
			return nil, err
		}
	}

	enumNames := sortedKeys(g.enums)
	constantNames := make(map[string]string)
	for _, name := range enumNames {
		enumGoName := goName(name)
		fmt.Fprintf(&output, "// %s is a LINE Thrift enum.\ntype %s int32\n\n", enumGoName, enumGoName)
		members := g.enums[name]
		if len(members) == 0 {
			continue
		}
		output.WriteString("const (\n")
		for _, member := range members {
			constant := enumGoName + goName(member.name)
			if constant == enumGoName {
				constant += strconv.FormatInt(member.value, 10)
			}
			if previous, exists := constantNames[constant]; exists {
				return nil, fmt.Errorf("enum constant %s collides between %s and %s", constant, previous, name)
			}
			constantNames[constant] = name
			fmt.Fprintf(&output, "\t%s %s = %d\n", constant, enumGoName, member.value)
		}
		output.WriteString(")\n\n")
	}

	for _, name := range sortedKeys(g.structs) {
		goType := goName(name)
		fmt.Fprintf(&output, "// %s is a LINE Thrift struct.\ntype %s struct {\n", goType, goType)
		fieldNames := make(map[string]string, len(g.structs[name]))
		for _, field := range g.structs[name] {
			fieldName := goName(field.Name)
			if previous, exists := fieldNames[fieldName]; exists {
				return nil, fmt.Errorf("field name %s collides in %s between %q and %q", fieldName, name, previous, field.Name)
			}
			fieldNames[fieldName] = field.Name
			fieldType, tag, err := g.fieldType(field)
			if err != nil {
				return nil, fmt.Errorf("field %s.%s: %w", name, field.Name, err)
			}
			fmt.Fprintf(&output, "\t%s %s `json:%q thrift:%q`\n", fieldName, fieldType, field.Name+",omitempty", tag)
		}
		output.WriteString("}\n\n")
	}
	return []byte(output.String()), nil
}

func (g *generator) fieldType(field fieldDefinition) (string, string, error) {
	switch {
	case len(field.Type) != 0:
		typeID, err := rawInt(field.Type)
		if err != nil {
			return "", "", err
		}
		goType := primitiveGoType(typeID)
		if field.Binary {
			goType = "[]byte"
		}
		return "*" + goType, fmt.Sprintf("%d,%d", field.ID, typeID), nil
	case field.Struct != "":
		if _, isEnum := g.enums[field.Struct]; isEnum {
			return "*" + goName(field.Struct), fmt.Sprintf("%d,8", field.ID), nil
		}
		if _, isStruct := g.structs[field.Struct]; isStruct {
			return "*" + goName(field.Struct), fmt.Sprintf("%d,12", field.ID), nil
		}
		return "any", fmt.Sprintf("%d,unknown", field.ID), nil
	case len(field.List) != 0:
		elementType, err := g.elementType(field.List, field.Binary)
		if err != nil {
			return "", "", err
		}
		goType, wireType := elementType.goType, elementType.wireType
		return "[]" + goType, fmt.Sprintf("%d,15,%d", field.ID, wireType), nil
	case len(field.Set) != 0:
		elementType, err := g.elementType(field.Set, false)
		if err != nil {
			return "", "", err
		}
		return "[]" + elementType.goType, fmt.Sprintf("%d,14,%d", field.ID, elementType.wireType), nil
	case len(field.Map) != 0 && len(field.Key) != 0:
		keyType, err := g.elementType(field.Key, false)
		if err != nil {
			return "", "", fmt.Errorf("map key type: %w", err)
		}
		valueType, err := g.elementType(field.Map, false)
		if err != nil {
			return "", "", fmt.Errorf("map value type: %w", err)
		}
		return fmt.Sprintf("map[%s]%s", keyType.goType, valueType.goType),
			fmt.Sprintf("%d,13,%d,%d", field.ID, keyType.wireType, valueType.wireType), nil
	default:
		return "any", fmt.Sprintf("%d,unknown", field.ID), nil
	}
}

func (g *generator) elementType(raw json.RawMessage, binary bool) (struct {
	goType   string
	wireType int
}, error) {
	if typeID, err := rawInt(raw); err == nil {
		goType := primitiveGoType(typeID)
		if binary && typeID == 11 {
			goType = "[]byte"
		}
		return struct {
			goType   string
			wireType int
		}{goType: goType, wireType: typeID}, nil
	}
	var name string
	if err := json.Unmarshal(raw, &name); err != nil {
		return struct {
			goType   string
			wireType int
		}{}, fmt.Errorf("unsupported element descriptor %s", raw)
	}
	if _, isEnum := g.enums[name]; isEnum {
		return struct {
			goType   string
			wireType int
		}{goType: goName(name), wireType: 8}, nil
	}
	if _, isStruct := g.structs[name]; isStruct {
		return struct {
			goType   string
			wireType int
		}{goType: "*" + goName(name), wireType: 12}, nil
	}
	return struct {
		goType   string
		wireType int
	}{goType: "any", wireType: 12}, nil
}

func addTypeName(names map[string]string, sourceName string) error {
	generated := goName(sourceName)
	if generated == "" {
		return fmt.Errorf("schema name %q cannot be converted to a Go identifier", sourceName)
	}
	if previous, exists := names[generated]; exists {
		return fmt.Errorf("generated type name %s collides between %q and %q", generated, previous, sourceName)
	}
	names[generated] = sourceName
	return nil
}

func goName(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool {
		return !('a' <= r && r <= 'z') && !('A' <= r && r <= 'Z') && !('0' <= r && r <= '9')
	})
	var name strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		name.WriteString(strings.ToUpper(part[:1]))
		name.WriteString(part[1:])
	}
	result := name.String()
	if result != "" && '0' <= result[0] && result[0] <= '9' {
		result = "X" + result
	}
	return result
}

func primitiveGoType(typeID int) string {
	switch typeID {
	case 2:
		return "bool"
	case 3:
		return "int8"
	case 4:
		return "float64"
	case 6:
		return "int16"
	case 8:
		return "int32"
	case 10:
		return "int64"
	case 11:
		return "string"
	default:
		return "any"
	}
}

func rawInt(data json.RawMessage) (int, error) {
	var value int
	if err := json.Unmarshal(data, &value); err != nil {
		return 0, fmt.Errorf("expected numeric Thrift type, got %s", data)
	}
	return value, nil
}

func sortedKeys[T any](values map[string]T) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
